#!/usr/bin/env node
// Regenerates lib/landing/world-mask.ts — the land shape behind GlyphField.
//
//   npm i --no-save world-atlas@2 topojson-client@3
//   node scripts/gen-world-mask.mjs [width=288]
//
// Natural Earth 1:50m land (public domain) via world-atlas (ISC). The two
// packages are needed only here, so they are not dependencies: the output is a
// 5 KB committed file and the app never loads map data at run time.
// Point-in-polygon over ~1,400 rings with 4×4 supersampling: about a minute.
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';

const require = createRequire(import.meta.url);
const topo = require('world-atlas/land-50m.json');
const { feature } = require('topojson-client');

const W = Number(process.argv[2]) || 288;
const LAT0 = 78, LAT1 = -57, LON0 = -169, LON1 = 191;
const H = Math.round((W * (LAT0 - LAT1)) / (LON1 - LON0));

const polys = [];
for (const f of feature(topo, topo.objects.land).features) {
  const g = f.geometry;
  for (const rings of g.type === 'Polygon' ? [g.coordinates] : g.coordinates) {
    // Longitudes west of LON0 move to the far right, so Chukotka joins Alaska's side.
    const rr = rings.map((r) => r.map(([x, y]) => [x < LON0 ? x + 360 : x, y]));
    let minx = Infinity, maxx = -Infinity, miny = Infinity, maxy = -Infinity;
    for (const r of rr) for (const [x, y] of r) { minx = Math.min(minx, x); maxx = Math.max(maxx, x); miny = Math.min(miny, y); maxy = Math.max(maxy, y); }
    polys.push({ rr, minx, maxx, miny, maxy });
  }
}
const inside = (x, y) => {
  for (const p of polys) {
    if (x < p.minx || x > p.maxx || y < p.miny || y > p.maxy) continue;
    let c = false;
    for (const r of p.rr) {
      for (let i = 0, j = r.length - 1; i < r.length; j = i++) {
        const [xi, yi] = r[i], [xj, yj] = r[j];
        if ((yi > y) !== (yj > y) && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) c = !c;
      }
    }
    if (c) return true;
  }
  return false;
};

const bits = new Uint8Array(Math.ceil((W * H) / 8));
for (let j = 0; j < H; j++) {
  for (let i = 0; i < W; i++) {
    let hit = 0;
    for (let sy = 0; sy < 4; sy++) for (let sx = 0; sx < 4; sx++) {
      const lon = LON0 + ((i + (sx + 0.5) / 4) / W) * (LON1 - LON0);
      const lat = LAT0 - ((j + (sy + 0.5) / 4) / H) * (LAT0 - LAT1);
      if (inside(lon, lat)) hit++;
    }
    if (hit >= 8) { const k = j * W + i; bits[k >> 3] |= 1 << (k & 7); }
  }
}

writeFileSync(new URL('../lib/landing/world-mask.ts', import.meta.url), `// The world, as a 1-bit land mask — GENERATED by scripts/gen-world-mask.mjs, do not edit.
//
// Natural Earth 1:50m land (public domain), via the world-atlas package (ISC),
// rasterised to an equirectangular ${W}×${H} grid with 4×4 supersampling:
// a cell is land when at least half of it is. Longitudes ${LON0}…${LON1}
// (so Chukotka sits beside Alaska), latitudes ${LAT0}…${LAT1} (no
// Antarctica — it is a background, not an atlas). Bits are row-major from the
// top-left, least significant bit first. About 5 KB; read by GlyphField.
export const WORLD_MASK = {
  width: ${W},
  height: ${H},
  bits: '${Buffer.from(bits).toString('base64')}',
} as const;
`);
console.log(`lib/landing/world-mask.ts — ${W}×${H}`);
