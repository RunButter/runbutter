#!/usr/bin/env node
/**
 * Bundle the whole schema into ONE file: `supabase/schema.sql`.
 *
 * WHY THIS EXISTS. `npm run migrate` is the better path and stays the one the
 * docs recommend — it is a single command, it is idempotent, and it records
 * what it applied. But it needs a connection string with the SESSION pooler,
 * and plenty of people meet Supabase through its SQL editor in a browser and
 * would rather paste something once than find a password in a settings page.
 * This is for them.
 *
 * IT IS A CONCATENATION, NOT A DUMP. `pg_dump` would produce a smaller file and
 * a subtly different one: extensions land in a different schema on Supabase,
 * grants to `anon`/`authenticated` have to survive, and any difference between
 * "what the dump recreates" and "what the migrations do" is a difference nobody
 * would notice until a stranger's install behaved unlike ours. This file is the
 * same SQL, in the same order, so there is nothing to translate.
 *
 * IT SEEDS `schema_migrations` AT THE END, with the same checksums the runner
 * computes. Without that, a pasted schema looks untouched to the runner and the
 * next `npm run migrate` would try to apply all 106 files to a populated
 * database — the legacy ones are not idempotent, so that is a real failure and
 * not a tidy one. With it, the two paths converge: paste once, then update with
 * the runner forever after.
 *
 * Regenerate with `npm run bundle:sql`. Never edit supabase/schema.sql by hand.
 */
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { LEGACY_ORDER } from './lib/legacy-order.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const MIGRATIONS = join(ROOT, 'supabase', 'migrations');
const LEGACY = join(ROOT, 'supabase', 'legacy');
const BOOTSTRAP = join(ROOT, 'supabase', 'bootstrap.sql');
const OUT = join(ROOT, 'supabase', 'schema.sql');

// Identical to the runner's, or every file would look changed on the first
// `npm run migrate` after a paste.
const sha = (s) => createHash('sha256').update(s).digest('hex').slice(0, 12);

const lit = (s) => `'${String(s).replace(/'/g, "''")}'`;

const files = [];
if (existsSync(BOOTSTRAP)) files.push({ name: 'bootstrap.sql', path: BOOTSTRAP, kind: 'bootstrap' });
if (existsSync(LEGACY)) {
  for (const f of LEGACY_ORDER) {
    const p = join(LEGACY, f);
    if (existsSync(p)) files.push({ name: `legacy/${f}`, path: p, kind: 'legacy' });
  }
}
for (const f of readdirSync(MIGRATIONS).filter((f) => f.endsWith('.sql')).sort()) {
  files.push({ name: f, path: join(MIGRATIONS, f), kind: 'migration' });
}

const parts = [];
const ledger = [];

parts.push(`-- RunButter — the whole schema, in one file.
--
-- GENERATED by \`npm run bundle:sql\` from supabase/bootstrap.sql,
-- supabase/legacy/ and supabase/migrations/. Do not edit this file: the next
-- regeneration overwrites it, and the migrations are the source of truth.
--
-- HOW TO USE IT
--   Supabase → SQL Editor → paste → Run. It takes a minute or two; it is a lot
--   of SQL. Then come back for updates with \`npm run migrate\`, which will see
--   everything here as already applied.
--
-- FOR ANY OTHER POSTGRES
--   psql "$DATABASE_URL" -f supabase/schema.sql
--
-- WHAT IS IN IT
--   ${files.length} files: bootstrap (a no-op on a real Supabase project — it only creates
--   the roles and the auth/storage objects a bare Postgres lacks), the legacy
--   ATS schema, then every numbered migration in order.
--
-- ONE THING TO KNOW: this is for a NEW, EMPTY database. On a project that has
-- already run some migrations, use \`npm run migrate\` instead — it applies only
-- what is missing. The legacy files here are not idempotent.

set statement_timeout = 0;
set lock_timeout = 0;
set client_min_messages = warning;

create table if not exists schema_migrations (
  name        text primary key,
  checksum    text not null,
  applied_at  timestamptz not null default now(),
  kind        text not null default 'migration'
);
`);

for (const f of files) {
  const sql = readFileSync(f.path, 'utf8');
  parts.push(`\n-- ${'═'.repeat(74)}\n-- ${f.name}\n-- ${'═'.repeat(74)}\n${sql.trimEnd()}\n`);
  // bootstrap is not a migration and the runner never records it.
  if (f.kind !== 'bootstrap') ledger.push({ name: f.name, sum: sha(sql), kind: f.kind });
}

parts.push(`
-- ${'═'.repeat(74)}
-- The ledger: everything above, marked applied.
--
-- This is what lets \`npm run migrate\` take over from here instead of trying to
-- replay all of it against a database that already has it.
-- ${'═'.repeat(74)}
insert into schema_migrations (name, checksum, kind) values
${ledger.map((l) => `  (${lit(l.name)}, ${lit(l.sum)}, ${lit(l.kind)})`).join(',\n')}
on conflict (name) do update set checksum = excluded.checksum, applied_at = now();

notify pgrst, 'reload schema';
`);

const out = parts.join('');
writeFileSync(OUT, out);
console.log(`supabase/schema.sql — ${files.length} files, ${(out.length / 1024).toFixed(0)} KB`);
